import { createSignal, Show } from "solid-js"
import { QueryBoundary } from "../../components/QueryBoundary"
import { type Column, Table } from "../../components/Table"
import { TableSkeleton } from "../../components/TableSkeleton"
import { errorMessage } from "../../lib/api/errors"
import {
  type ReportDeliveryStatus,
  reportDeliveryStatus,
  type UsageReportDeliveryView,
  type UsageReportListItem,
} from "../../lib/api/usage-reports"
import { formatDate } from "../../lib/format"
import { useDeliverUsageReport, useUsageReports } from "../../lib/queries/usage"
import styles from "./UsageReports.module.scss"

/**
 * The stored weekly reports: which weeks exist and where delivery of each stands. A report is
 * generated by the scheduler and delivered by its own task; the one control here is **Resend**
 * (issue #229), which posts a stored week to the Discord channel again through the same
 * claim-before-post path the task uses. The button says what it does, and the outcome the server
 * returns — including a delivery that *failed* — is shown against the row, never guessed.
 *
 * Its own query and its own error state, outside the summary's boundary: a failing rollup should
 * not hide whether last week's report went out, and the reverse.
 */
export function UsageReports() {
  const reports = useUsageReports()
  const deliver = useDeliverUsageReport()
  // One notice at a time, keyed to the row it belongs to: a re-send is a deliberate click, and the
  // answer the server gave that click is what the operator reads next.
  const [notice, setNotice] = createSignal<{ periodStart: string; text: string } | null>(null)
  // Weeks with a re-send in flight, tracked per row: the mutation store only reports its latest
  // call, and the busy state belongs to the row that was clicked — never to the whole list (#270).
  const [pendingWeeks, setPendingWeeks] = createSignal<ReadonlySet<string>>(new Set())

  const resend = (periodStart: string) => {
    // The guard behind `aria-disabled`: the button stays focusable, so the click still lands here.
    if (pendingWeeks().has(periodStart)) return
    setPendingWeeks((prev) => new Set(prev).add(periodStart))
    setNotice({ periodStart, text: "Posting to the channel…" })
    deliver.mutate(periodStart, {
      onSuccess: (view) => setNotice({ periodStart, text: deliveryNotice(view) }),
      onError: (error) => setNotice({ periodStart, text: errorMessage(error) }),
      onSettled: () =>
        setPendingWeeks((prev) => {
          const next = new Set(prev)
          next.delete(periodStart)
          return next
        }),
    })
  }

  const columns: readonly Column<UsageReportListItem>[] = [
    {
      id: "week",
      header: "Week",
      cell: (row) => `${row.periodStart} to ${row.periodEnd}`,
    },
    {
      id: "generated",
      header: "Generated",
      cell: (row) => formatDate(row.generatedAt),
    },
    {
      id: "delivery",
      header: "Delivery",
      cell: (row) => <span class={styles.status}>{statusLabel(row)}</span>,
    },
    {
      id: "resend",
      header: "Resend",
      cell: (row) => (
        <div class={styles.resend}>
          <button
            // `aria-disabled` + the guard in `resend`, never `disabled`: a `disabled` button drops
            // keyboard focus and is invisible to screen readers, so a busy row would silently
            // strand the operator on it (#270). `aria-busy` announces the in-flight post.
            aria-busy={pendingWeeks().has(row.periodStart) || undefined}
            aria-disabled={pendingWeeks().has(row.periodStart) || undefined}
            aria-label={`Post the week of ${row.periodStart} to the Discord channel again`}
            class={styles.resendButton}
            onClick={() => resend(row.periodStart)}
            title="Posts this stored week's report to the Discord channel again"
            type="button"
          >
            Resend to channel
          </button>
          <Show when={notice()?.periodStart === row.periodStart}>
            <span class={styles.resendNotice} role="status">
              {notice()?.text}
            </span>
          </Show>
        </div>
      ),
    },
  ]

  return (
    <section aria-label="Weekly reports" class={styles.panel}>
      <h2 class={styles.title}>Weekly reports</h2>
      <QueryBoundary
        errorTitle="Weekly reports could not be loaded"
        loading={<TableSkeleton label="Loading weekly reports" rows={3} />}
        query={reports}
      >
        {(rows) => (
          <Table
            caption="Stored weekly usage reports, newest week first. Weeks run Monday to Monday, UTC."
            columns={columns}
            emptyMessage="No weekly report has been generated yet."
            rowId={(row) => row.periodStart}
            rows={rows}
          />
        )}
      </QueryBoundary>
    </section>
  )
}

const LABEL: Readonly<Record<ReportDeliveryStatus, string>> = {
  pending: "Pending",
  not_configured: "Not configured",
  sent: "Sent",
  failed: "Failed",
}

/**
 * An unrecognised status is shown as written: the column is text so a later release can add a
 * state, and an old console should say what the server said rather than hide the row.
 */
function statusLabel(row: UsageReportListItem): string {
  const status = reportDeliveryStatus(row.deliveryStatus)
  if (status === undefined) return row.deliveryStatus
  switch (status) {
    case "sent":
      return row.deliveredAt === null
        ? LABEL.sent
        : `${LABEL.sent} · ${formatDate(row.deliveredAt)}`
    case "failed":
      return `${LABEL.failed} · ${row.deliveryAttempts} attempt${row.deliveryAttempts === 1 ? "" : "s"}`
    case "pending":
    case "not_configured":
      return LABEL[status]
  }
}

/** The server's own outcome for the click, in one sentence; a failure names its redacted reason. */
function deliveryNotice(view: UsageReportDeliveryView): string {
  switch (reportDeliveryStatus(view.deliveryStatus)) {
    case "sent":
      return "Posted to the channel."
    case "failed":
      return `Delivery failed: ${view.lastError ?? "the stored delivery status is failed"}`
    case "not_configured":
      return "No Discord webhook is configured (USAGE_REPORT_DISCORD_WEBHOOK_URL)."
    default:
      return `The server answered: ${view.deliveryStatus}`
  }
}
